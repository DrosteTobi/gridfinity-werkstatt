export function moduleName(moduleId: string, locale: Locale): string {
  return moduleNames[moduleId]?.[locale] ?? moduleId;
}

export function categoryLabel(
  locale: Locale,
  category: ModuleCategory,
): string {
  if (category === "bin") return t(locale, "catBin");
  if (category === "baseplate") return t(locale, "catBaseplate");
  return t(locale, "catDivider");
}

export function moduleNamesBoth(moduleId: string) {
  return moduleNames[moduleId] ?? { de: moduleId, en: moduleId };
}
